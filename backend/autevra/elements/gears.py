"""External spur gear pairs (ISO 21771 geometry on the ISO 53 basic rack; ISO 6336-style
nominal stresses).

- Reference d = m z, base db = d cos alpha, pitch p = pi m, base pitch pb = p cos alpha.
- Profile shift x: working pressure angle from
  inv(alpha_w) = inv(alpha) + 2 tan(alpha) (x1 + x2) / (z1 + z2); centre distance
  a_w = a cos(alpha) / cos(alpha_w) with a = m (z1 + z2) / 2; tip diameters
  da = d + 2 m (ha* + x - k) with the tip shortening k m = a + (x1 + x2) m - a_w;
  root df = d - 2 m (ha* + c* - x).
- Transverse contact ratio
  eps = [sqrt(ra1^2 - rb1^2) + sqrt(ra2^2 - rb2^2) - a_w sin(alpha_w)] / pb.
- Undercut: a gear generated by the rack undercuts when x < ha* - z sin^2(alpha) / 2
  (z_min = 17 at 20 deg with no shift). Tooth tip thickness checked against 0.25 m.
- Tooth form: involute flanks from the base (or root) circle to the tip, half tooth angle
  psi(r) = s / (2 r_ref) + inv(alpha) - inv(alpha_r); the root fillet (trochoid) is
  replaced by a radial line, so the built solid is for layout and mass, not for tooth
  contact analysis.
- Loads: tangential force Ft = 2000 T1 / d1 (T1 in N·m); Lewis bending
  sigma = Kv Ft / (b m Y) with the Lewis form factor Y (Shigley table 14-2) and the
  Barth velocity factor Kv = (6.1 + V) / 6.1 (cut or milled teeth); nominal contact stress
  sigma_H0 = Z_E Z_H Z_eps sqrt(Ft (u + 1) / (b d1 u)), Z_E = 189.8 sqrt(MPa) for steel on
  steel, Z_H = sqrt(2 / (cos^2 alpha tan alpha_w)), Z_eps = sqrt((4 - eps) / 3). The ISO
  6336 application, dynamic and load-distribution factors are not applied to sigma_H0.
"""

import math

from pydantic import BaseModel, Field, model_validator

LEWIS_Y = [
    (12, 0.245),
    (13, 0.261),
    (14, 0.277),
    (15, 0.290),
    (16, 0.296),
    (17, 0.303),
    (18, 0.309),
    (19, 0.314),
    (20, 0.322),
    (21, 0.328),
    (22, 0.331),
    (24, 0.337),
    (26, 0.346),
    (28, 0.353),
    (30, 0.359),
    (34, 0.371),
    (38, 0.384),
    (43, 0.397),
    (50, 0.409),
    (60, 0.422),
    (75, 0.435),
    (100, 0.447),
    (150, 0.460),
    (300, 0.472),
    (400, 0.480),
]
Z_E_STEEL = 189.8


def inv(a: float) -> float:
    return math.tan(a) - a


def inv_inverse(v: float) -> float:
    a = (3.0 * v) ** (1.0 / 3.0) if v > 0 else 0.0
    for _ in range(50):
        f = inv(a) - v
        a -= f / math.tan(a) ** 2 if a > 0 else 0.0
        if abs(f) < 1e-15:
            break
    return a


def lewis_y(z: int) -> float:
    if z <= LEWIS_Y[0][0]:
        return LEWIS_Y[0][1]
    for (z0, y0), (z1, y1) in zip(LEWIS_Y, LEWIS_Y[1:], strict=False):
        if z <= z1:
            return y0 + (y1 - y0) * (z - z0) / (z1 - z0)
    return LEWIS_Y[-1][1]


class GearPairIn(BaseModel):
    module: float = Field(2.0, gt=0.1, le=50.0)
    z1: int = Field(20, ge=6, le=400)
    z2: int = Field(40, ge=6, le=400)
    pressure_angle: float = Field(20.0, ge=14.5, le=30.0)
    x1: float = Field(0.0, ge=-1.0, le=1.5)
    x2: float = Field(0.0, ge=-1.0, le=1.5)
    face_width: float = Field(20.0, gt=0.5, le=2000.0)
    addendum: float = Field(1.0, gt=0.5, le=1.5)  # ha*
    clearance: float = Field(0.25, ge=0.1, le=0.5)  # c*
    torque_Nm: float = Field(0.0, ge=0.0)  # on the pinion (gear 1)  # noqa: N815
    rpm: float = Field(0.0, ge=0.0)  # pinion speed
    bore1: float = Field(0.0, ge=0.0)  # mm, 0 = solid
    bore2: float = Field(0.0, ge=0.0)

    @model_validator(mode="after")
    def _sizes(self) -> "GearPairIn":
        for z, bore, name in ((self.z1, self.bore1, "1"), (self.z2, self.bore2, "2")):
            root = self.module * (z - 2.0 * (self.addendum + self.clearance))
            if bore and bore >= 0.8 * root:
                raise ValueError(f"bore of gear {name} leaves no rim under the teeth")
        return self


def _gear(
    m: float, z: int, x: float, alpha: float, ha: float, c: float, k: float
) -> dict[str, float]:
    d = m * z
    s = m * (math.pi / 2.0 + 2.0 * x * math.tan(alpha))
    da = d + 2.0 * m * (ha + x - k)
    df = d - 2.0 * m * (ha + c - x)
    db = d * math.cos(alpha)
    ra, rb = da / 2.0, db / 2.0
    alpha_a = math.acos(min(rb / ra, 1.0))
    psi_a = s / d + inv(alpha) - inv(alpha_a)  # half tooth angle at the tip
    x_min = ha - z * math.sin(alpha) ** 2 / 2.0
    return {
        "z": z,
        "x": x,
        "d": d,
        "da": da,
        "df": df,
        "db": db,
        "s": s,
        "tip_thickness": 2.0 * ra * psi_a,
        "x_min": x_min,
        "undercut": x < x_min - 0.01,
    }  # under 0.01 m: negligible


def pair(g: GearPairIn) -> dict:
    m, alpha = g.module, math.radians(g.pressure_angle)
    a = m * (g.z1 + g.z2) / 2.0
    xs = g.x1 + g.x2
    alpha_w = inv_inverse(inv(alpha) + 2.0 * math.tan(alpha) * xs / (g.z1 + g.z2)) if xs else alpha
    a_w = a * math.cos(alpha) / math.cos(alpha_w)
    k = (a + xs * m - a_w) / m  # tip shortening factor
    g1 = _gear(m, g.z1, g.x1, alpha, g.addendum, g.clearance, k)
    g2 = _gear(m, g.z2, g.x2, alpha, g.addendum, g.clearance, k)
    pb = math.pi * m * math.cos(alpha)
    approach = math.sqrt((g1["da"] / 2) ** 2 - (g1["db"] / 2) ** 2)
    recess = math.sqrt((g2["da"] / 2) ** 2 - (g2["db"] / 2) ** 2)
    eps = (approach + recess - a_w * math.sin(alpha_w)) / pb
    u = g.z2 / g.z1
    out: dict = {
        "ratio": u,
        "centre_distance": a_w,
        "reference_centre_distance": a,
        "working_pressure_angle": math.degrees(alpha_w),
        "tip_shortening": k,
        "pitch": math.pi * m,
        "base_pitch": pb,
        "contact_ratio": eps,
        "gear1": g1,
        "gear2": g2,
    }
    warnings = []
    for name, gg in (("pinion", g1), ("gear", g2)):
        if gg["undercut"]:
            warnings.append(
                f"Undercut on the {name}: z = {gg['z']} needs a profile shift "
                f"x ≥ {gg['x_min']:.3f} "
                f"(z < 17 at 20° unshifted)."
            )
        if gg["tip_thickness"] < 0.25 * m:
            warnings.append(
                f"{name.capitalize()} teeth are nearly pointed "
                f"(tip {gg['tip_thickness']:.2f} mm < 0.25 m)."
            )
    if eps < 1.2:
        warnings.append(f"Contact ratio {eps:.2f} < 1.2: rough running.")
    if g.torque_Nm > 0:
        ft = 2000.0 * g.torque_Nm / g1["d"]
        v = math.pi * g1["d"] / 1000.0 * g.rpm / 60.0
        kv = (6.1 + v) / 6.1
        zh = math.sqrt(2.0 / (math.cos(alpha) ** 2 * math.tan(alpha_w)))
        ze = math.sqrt(max(4.0 - eps, 0.1) / 3.0)
        sh = Z_E_STEEL * zh * ze * math.sqrt(ft * (u + 1.0) / (g.face_width * g1["d"] * u))
        out |= {
            "tangential_force_N": ft,
            "pitch_line_velocity": v,
            "Kv": kv,
            "radial_force_N": ft * math.tan(alpha_w),
            "Z_H": zh,
            "Z_eps": ze,
            "bending_pinion": kv * ft / (g.face_width * m * lewis_y(g.z1)),
            "bending_gear": kv * ft / (g.face_width * m * lewis_y(g.z2)),
            "lewis_Y1": lewis_y(g.z1),
            "lewis_Y2": lewis_y(g.z2),
            "contact_stress": sh,
            "power_kW": g.torque_Nm * g.rpm * 2.0 * math.pi / 60.0 / 1000.0,
            "output_torque_Nm": g.torque_Nm * u,
        }
    out["warnings"] = warnings
    return out


def tooth_outline(
    m: float, z: int, x: float, alpha_deg: float, da: float, df: float, flank_points: int = 10
) -> list[tuple[float, float]]:
    """One tooth as a closed polygon (CCW), symmetric about +Y, from just inside the root
    circle to the tip. Radial line from the root to the base circle where df < db."""
    alpha = math.radians(alpha_deg)
    r_ref, rb, ra, rf = m * z / 2.0, m * z * math.cos(alpha) / 2.0, da / 2.0, df / 2.0
    s = m * (math.pi / 2.0 + 2.0 * x * math.tan(alpha))
    half_ref = s / (2.0 * r_ref)

    def psi(r: float) -> float:
        ar = math.acos(min(rb / r, 1.0))
        return half_ref + inv(alpha) - inv(ar)

    r0 = max(rb, rf)
    right: list[tuple[float, float]] = []  # from root to tip, x > 0
    inner = rf - 0.15 * m  # sink into the root disc so the union is robust
    half_root = min(psi(r0), math.pi / z * 0.98)
    right.append((inner * math.sin(half_root), inner * math.cos(half_root)))
    if rf < rb:
        right.append((rf * math.sin(half_root), rf * math.cos(half_root)))
    for i in range(flank_points + 1):
        r = r0 + (ra - r0) * i / flank_points
        p = max(psi(r), 0.0)
        right.append((r * math.sin(p), r * math.cos(p)))
    left = [(-px, py) for px, py in reversed(right)]
    pts = right + left  # right flank up, tip, left flank down
    out: list[tuple[float, float]] = []
    for p in pts:
        if not out or math.dist(p, out[-1]) > 1e-6:
            out.append((round(p[0], 6), round(p[1], 6)))
    return out


def gear_part(
    name: str,
    m: float,
    gear: dict,
    alpha_deg: float,
    width: float,
    bore: float,
    at: tuple[float, float, float],
    rz: float,
    color: tuple[float, float, float],
) -> dict:
    """A PartDoc for one gear: root disc, one involute tooth patterned z times, and a bore."""
    z = int(gear["z"])
    rf = gear["df"] / 2.0
    feats: list[dict] = [
        {
            "id": "blank",
            "name": "Root disc",
            "type": "cylinder",
            "radius": rf,
            "height": width,
            "axis": "z",
            "at": {"z": width / 2.0},
        },
        {
            "id": "tooth",
            "name": "Involute tooth",
            "type": "extrude",
            "plane": "xy",
            "depth": width,
            "points": tooth_outline(m, z, gear["x"], alpha_deg, gear["da"], gear["df"]),
        },
        {
            "id": "teeth",
            "name": f"{z} teeth",
            "type": "circular_pattern",
            "count": z,
            "axis": "z",
            "angle": 360.0,
        },
    ]
    if bore > 0:
        feats.append(
            {
                "id": "bore",
                "name": "Bore",
                "type": "cylinder",
                "op": "cut",
                "radius": bore / 2.0,
                "height": width * 1.2,
                "axis": "z",
                "at": {"z": width / 2.0},
            }
        )
    return {
        "name": name,
        "features": feats,
        "color": color,
        "finish": "metal",
        "at": {"x": at[0], "y": at[1], "z": at[2], "rz": rz},
        "parameters": {"module": m, "teeth": float(z), "face_width": width},
    }


def pair_parts(g: GearPairIn) -> list[dict]:
    """Both gears placed in mesh along +X: a pinion tooth points at the gear, which shows a
    tooth space back."""
    res = pair(g)
    a_w = res["centre_distance"]
    p1 = gear_part(
        f"Pinion z{g.z1} m{g.module:g}",
        g.module,
        res["gear1"],
        g.pressure_angle,
        g.face_width,
        g.bore1,
        (0.0, 0.0, 0.0),
        -90.0,
        (0.72, 0.74, 0.78),
    )
    p2 = gear_part(
        f"Gear z{g.z2} m{g.module:g}",
        g.module,
        res["gear2"],
        g.pressure_angle,
        g.face_width,
        g.bore2,
        (a_w, 0.0, 0.0),
        90.0 + 180.0 / g.z2,
        (0.80, 0.62, 0.30),
    )
    return [p1, p2]
